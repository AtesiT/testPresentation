def card(s, x, y, w, h, accent=None, fill=PANEL, line=BORDER):
    rect(s, x, y, w, h, fill=fill, line=line, lw=0.75)
    if accent:
        rect(s, x, y, 0.05, h, fill=accent)


def kpi(s, x, y, w, h, value, label, color=CYAN, vsize=24, lsize=10):
    card(s, x, y, w, h, accent=color)
    text(s, x + 0.20, y + 0.16, w - 0.3, 0.42, value, size=vsize, color=color, bold=True)
    text(s, x + 0.20, y + h - 0.56, w - 0.3, 0.46, label, size=lsize, color=MUTED,
         line_spacing=1.05)


def caption(s, x, y, w, s_text, color=DIM, size=9, align='l'):
    text(s, x, y, w, 0.3, s_text, size=size, color=color, italic=True, align=align)


